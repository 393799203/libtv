import type { PrevizObjectType, Vec3 } from './types';

/**
 * 场景组合件（一键整套布景）。
 * 只用已有的元素类型拼装，坐标单位是米，几何体从 y=0 起建，
 * 所以 position 的 y 一般给 0（薄片类如水洼、地垫给 0.01 抬一点避免闪面）。
 * 应用时是「追加到当前场景」，不动你已经摆好的东西。
 */
export interface PresetObject {
  type: PrevizObjectType;
  name: string;
  position: Vec3;
  rotation: Vec3;
  scale: Vec3;
  color?: string;
}
export interface ScenePreset {
  key: string;
  label: string;
  hint: string;
  objects: PresetObject[];
}

// 简写：类型 / 名字 / 位置 / 缩放 / 旋转(默认不动) / 颜色(默认跟随主题色)
function o(
  type: PrevizObjectType,
  name: string,
  position: Vec3,
  scale: Vec3,
  rotation: Vec3 = [0, 0, 0],
  color?: string
): PresetObject {
  return { type, name, position, rotation, scale, ...(color ? { color } : {}) };
}

