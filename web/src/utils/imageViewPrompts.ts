/**
 * 视图（三视图/四视图/六视图）与画质提升的提示词模板。
 *
 * 这些模板与后端 `server/internal/llm/prompt.go` 里脚本节点自动追加的
 * 【角色四视图】【场景四视图】【道具六视图】保持同一套约定，原因有两个：
 *  1. 宫格布局必须一致，切分参数才能自动预设（角色 1×4 / 场景 2×2 / 道具 2×3）
 *  2. 用户从"资产流程生成的四视图"和"图片节点上生成的三视图"得到的东西应当是同类产物
 *
 * 两条踩过的坑，改模板时务必守住：
 *
 * 【1】refToken 必须出现在返回的文本里。后端按它解析参考图（mentions），
 *      漏了就等于**不带参考图**去生成。`scene4` / `prop6` 曾经就漏了 ——
 *      因为场景/道具的一致性描述跟角色那套（长相/发型/服装）不通用，
 *      当时干脆没拼 tail，结果连 refToken 一起丢了，生成出来的场景跟原图毫无关系。
 *
 * 【2】视角要按"专业产线在用什么"来定，不能照着角色那套环拍套。
 *      · 角色/道具是**物体**：环拍（正/背/左/右/顶/底）才对，专业上叫六视图/正交投影视图；
 *      · 场景是**空间**：环拍四面墙（正/左45°/右45°/背）信息高度重复，做背景板根本用不上。
 *        专业设定的组合是「平面图 + 立面图 + 透视图」（建筑制图那套）：
 *          俯视平面图  → 空间布局、动线、家具相互关系
 *          正面立面图  → 正投影、无透视，可直接当背景板的"正打"视图
 *          侧面立面图  → 补另一面墙，与正立面同地平线/同层高
 *          斜四分之三透视图 → 人眼高度，表现纵深、体量、光影
 *        所以场景四视图用「平面 + 正立面 + 侧立面 + 斜透视」，而不是四个环拍角度。
 *        立面图与平面图必须写明**正投影/无透视畸变**（否则模型会画出透视，图就废了）。
 *
 * 另外：宫格排布要跟 VIEW_PRESETS 的 rows/cols 一一对应，且都要求"各格等比等分（不要画白色分割线）+
 * 格内无文字水印"——白边是切分时 trim 内缩的依据，文字/水印被画进某格那张单图就废了。
 */

/** refToken 形如 `[[m:<nodeId>]]`，由 PromptEditor 渲染成 @标签，后端按它解析参考图 */
export type ViewKind = 'character3' | 'character4' | 'scene4' | 'prop6';

export interface ViewPreset {
  kind: ViewKind;
  label: string;
  hint: string;
  /** 宫格行列：切分时自动预设，和提示词里要求的排布一致 */
  rows: number;
  cols: number;
}

export const VIEW_PRESETS: ViewPreset[] = [
  { kind: 'character3', label: '角色三视图', hint: '正面 / 侧面 / 背面 横排', rows: 1, cols: 3 },
  { kind: 'character4', label: '角色四视图', hint: '正脸特写 + 正/侧/背 全身横排（与脚本模板一致）', rows: 1, cols: 4 },
  {
    kind: 'scene4',
    label: '场景四视图',
    hint: '俯视平面 / 正面立面 / 侧面立面 / 斜四分之三透视，2×2 宫格（制图组合，不是环拍）',
    rows: 2,
    cols: 2,
  },
  { kind: 'prop6', label: '道具六视图', hint: '正/背/左/右/顶/底 正交投影，2×3 宫格', rows: 2, cols: 3 },
];

/** 按资产类型给出默认视图。 */
export function defaultViewKindForAsset(assetType?: string): ViewKind {
  if (assetType === 'scene') return 'scene4';
  if (assetType === 'prop') return 'prop6';
  // 角色资产 = 脚本模板追加的【角色四视图】（1×4：正脸近景特写 + 正面/侧面/背面全身）。
  // 这里原来给 character3（1×3）—— 于是资产流程产出的 1×4 图在「切分宫格」里被预选成 1×3，
  // 切出来每格都不对（同一个资产、两个口径）。三视图是图片节点「生成视图」里的可选档，
  // 需要它时用户自己在下拉里选，不再当资产角色的默认。
  if (assetType === 'character') return 'character4';
  // 没有资产类型的普通图片节点：不知道它是几格图，横排三视图最通用
  return 'character3';
}

/**
 * 资产流程的「参考图」说明行（拼在资产描述末尾，asset 描述本身是文生图提示词）。
 *
 * 为什么要加这一句：资产描述里从来没有"以这张参考图为准"的约束（脚本模板只写了
 * 视图要求与宫格布局），而现在上传的原图会真的作为参考图传进去 —— 不写明，
 * 模型会把参考图当可有可无的装饰，生成结果照样和原图对不上。
 *
 * refToken 必须原样出现在返回的文本里：后端按 prompt 里的 `[[m:xxx]]` 过滤 mentions，
 * 找不到标记的引用会被静默丢掉（同文件头第 1 条坑），占位符发给模型前会被剥掉，
 * 所以这句话去掉标记后也必须读得通。
 */
export function buildAssetReferenceLine(refToken: string): string {
  return `\n\n以随本次请求提供的参考图（用户上传的原图）为准：主体的外貌与结构、配色、材质、画风必须与之一致，不要重新设计、不要替换元素、不要改变主体的身份与风格（参考图标记 ${refToken}）。`;
}

/** 宫格排布的公共要求。切分是纯几何等分（trimPx 默认 0），不需要白线做依据；
 *  原来要求"1px 白边隔离"等于让模型画白色分割线，是白线稿观感的一部分，改成极窄浅灰间隙。 */
const SHEET_RULES = '各宫格等比等分、每格内容居中且不越界，格与格之间只留极窄的浅灰间隙（不要画白色分割线、不要画外框、不要网格线、不要编号），格内不要出现任何文字、箭头、尺寸标注或水印。';

/**
 * 风格锁定，不能省：正向描述里"白底 / 纯白无缝 / 均匀柔和平光 / 不要投影阴影 / 正投影 /
 * 模型设定图 / 画清轮廓"叠在一起，图像模型会直接给白底线描稿 —— 实测第一个视图经常变成
 * 白色线条图。所以除了删掉那些诱导线稿的措辞，还必须明确要求彩色立体渲染。
 */
const STYLE_LOCK = '【彩色立体渲染】必须是成品级的彩色立体画面：明确的体积感与明暗过渡、材质高光与布料褶皱清晰（皮肤/布料/金属/木材质感分明）；不要线稿、不要描边、不要黑白单色、不要白模、不要工程制图或平面图标风格。';

/** 多视图的共同前提：参考图只提供"主体长什么样"，视角与构图必须按文字重建 */
const VIEW_REBUILD = '每一格都必须严格按上面写明的相机角度单独绘制、各格视角明显不同；严禁沿用参考图的相机角度与构图 —— 参考图只用来提供主体的外观、配色、材质与画风。';

/** 构造视图生成提示词。refToken 必须出现在文本里，否则后端会丢掉对应的 mentions。 */
