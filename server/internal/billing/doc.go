// Package billing 计费与退费模块（钱相关的唯一归属地）。
//
// 为什么单独成模块：钱的问题不能散落在执行器、看门狗、后台接口里各写一套。
// 这个包里放四件事，改价格、改退款规则、查对账都只需要看这里：
//
//	service.go  扣费与退费（按次/按秒/按字、分辨率档位、参考视频 6 折、充值）
//	pricing.go  价格管理（model_prices 的读写、后台价格页的种子数据）
//	policy.go   退款规则（什么情况自动退、什么情况交人工、对账状态取值）
//	ledger.go   上游任务对账账本（provider_tasks：下发/交付/待人工退费/已退费 + 人工退费动作）
//
// 依赖方向：billing → repository / model / llm。执行器（engine）、后台接口（handler）、
// 看门狗都只能**调用**这里，不能各写一份计费或退款逻辑。
//
// 两条硬规则（改代码时必须守住，改动前先读 policy.go）：
//   - 同一笔扣费只能退一次（幂等标记 + 对账行 CAS）；
//   - 已交付的节点绝不退费。
package billing
