// Package apperr 放置跨包共享的错误标记。
//
// 这一层刻意做成「叶子包」：不 import 任何 internal 包，供 engine（生产标记）、
// queue（消费标记）等互相不直接依赖的层共同引用，避免循环引用。
package apperr

import "errors"

// ErrNoRetry 标记「重试没有意义、而且重试本身有害」的失败：
// 队列遇到带此标记的错误不再安排重试（直接 ACK，执行状态已由 handler 落为 failed）。
//
// 典型场景：上游视频任务的轮询超时（llm/video.go）。
// 该次扣费已在节点内退还给用户、界面也已经显示「失败」，
// 自动重试会重新下发上游任务并**重新扣费** —— 一次用户以为失败的生成却扣了两次钱；
// 若重试恰好复用上次那个仍在跑的上游任务，则又变成「不扣费拿到视频」（免费出片）。
// 因此这类失败一律交给用户自己决定是否重试。
var ErrNoRetry = errors.New("不需要重试")
